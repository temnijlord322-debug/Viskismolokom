class Calculator {
public:
    std::string compute(const std::string& expr) const {
        std::istringstream iss(expr);
        double a, b; std::string op;
        if (!(iss >> a >> op >> b)) return "[не могу распознать]";
        std::ostringstream o;
        if (op == "+" || op == "плюс") o << a << " + " << b << " = " << (a + b);
        else if (op == "-" || op == "минус") o << a << " - " << b << " = " << (a - b);
        else if (op == "*" || op == "умножить") o << a << " * " << b << " = " << (a * b);
        else if (op == "/" || op == "делить") {
            if (b == 0) return "[на ноль делить нельзя]";
            o << a << " / " << b << " = " << (a / b);
        }
        else return "[неизвестная операция]";
        return o.str();
    }
    std::string solve_quadratic(double a, double b, double c) const {
        if (a == 0) return "[это не квадратное уравнение]";
        double D = b*b - 4*a*c;
        std::ostringstream o;
        o << "Уравнение: " << a << "x² + " << b << "x + " << c << " = 0\nD = " << D << "\n";
        if (D < 0) o << "D < 0 — корней нет";
        else if (D == 0) o << "D = 0 — один корень: x = " << (-b / (2*a));
        else {
            double x1 = (-b + std::sqrt(D)) / (2*a);
            double x2 = (-b - std::sqrt(D)) / (2*a);
            o << "D > 0 — два корня: x₁ = " << x1 << ", x₂ = " << x2;
        }
        return o.str();
    }
    std::string multiplication_table(int n) const {
        std::ostringstream o;
        o << "Таблица умножения на " << n << ":\n";
        for (int i = 1; i <= 10; ++i) o << "  " << n << " × " << i << " = " << (n * i) << "\n";
        return o.str();
    }
    std::string formula(const std::string& q) const {
        std::string qq = q;
        std::transform(qq.begin(), qq.end(), qq.begin(), ::tolower);
        for (auto& f : FORMULAS) {
            std::string n = f.name;
            std::transform(n.begin(), n.end(), n.begin(), ::tolower);
            if (n.find(qq) != std::string::npos)
                return "📐 " + f.name + ": " + f.formula + " (" + f.desc + ")";
        }
        return "[формула не найдена]";
    }
    std::string all_formulas() const {
        std::ostringstream o;
        o << "📐 ВСЕ ФОРМУЛЫ (" << FORMULAS.size() << "):\n";
        for (auto& f : FORMULAS) o << "  " << f.name << ": " << f.formula << "\n";
        return o.str();
    }
};

